"""Build app/js/crs-db.js: a curated list of coordinate systems with proj4 strings,
ESRI WKT (for .prj files), units and area of use. Run: python3 tools/build_crs_db.py"""
import json, re, sys, warnings
from pyproj import CRS
from pyproj.transformer import TransformerGroup
warnings.filterwarnings("ignore")

codes = [4326]
codes += [32600 + z for z in range(1, 61)] + [32700 + z for z in range(1, 61)]
codes += [
    4209, 20934, 20935, 20936,                      # Arc 1950 (Zambia, Zimbabwe, Malawi, Botswana)
    4210, 21035, 21036, 21037, 21095, 21096, 21097,  # Arc 1960 (Kenya, Tanzania, Uganda)
    4695, 3986, 3987, 3988, 3989, 3990, 3991,        # Katanga 1955 (DRC Copperbelt)
    4701, 3339, 3340, 3341, 3342,                    # IGCB 1955 (DRC)
    4046, 4048, 4049, 4050, 4051, 4056, 4057, 4058, 4059, 4060, 4061, 4062, 4063,  # RGRDC 2005
    4222, 22234, 22235, 22236,                       # Cape
    4148,                                            # Hartebeesthoek94 (the Lo systems use west/south axes and are not offered yet)
    4127, 2736, 2737,                                # Tete (Mozambique)
    4130, 3036, 3037,                                # Moznet
    4293, 29333,                                     # Schwarzeck (Namibia)
    4220, 22032, 22033,                              # Camacupa (Angola)
    4263, 26331, 26332, 26391, 26392, 26393,         # Minna (Nigeria)
    4201, 20135, 20136, 20137, 20138,                # Adindan
    4168, 2136, 2137,                                # Accra (Ghana)
    4739, 4322, 32235,                               # misc / WGS72
    4267, 4269, 3857,
]

def towgs84(geod):
    try:
        tg = TransformerGroup(geod, CRS.from_epsg(4326), always_xy=True)
    except Exception:
        return None
    for t in tg.transformers:
        p = t.to_proj4() or ""
        m = re.search(r"\+proj=helmert([^|]*?)(?=\+step|$)", p)
        if not m:
            continue
        seg = m.group(1)
        def g(k):
            mm = re.search(r"\+%s=([-\d.eE]+)" % k, seg)
            return float(mm.group(1)) if mm else 0.0
        x, y, z = g("x"), g("y"), g("z")
        rx, ry, rz, s = g("rx"), g("ry"), g("rz"), g("s")
        if "coordinate_frame" in seg:
            rx, ry, rz = -rx, -ry, -rz
        if rx or ry or rz or s:
            return [x, y, z, rx, ry, rz, s]
        return [x, y, z]
    return None

out, seen = [], set()
for code in codes:
    if code in seen:
        continue
    seen.add(code)
    try:
        c = CRS.from_epsg(code)
    except Exception as e:
        print("skip", code, e, file=sys.stderr); continue
    p4 = c.to_proj4().replace(" +type=crs", "")
    if "+towgs84" not in p4 and c.geodetic_crs.to_epsg() not in (4326,) and "WGS84" not in p4 and "+datum=" not in p4:
        tw = towgs84(c.geodetic_crs)
        if tw:
            p4 = p4.replace(" +no_defs", " +towgs84=" + ",".join(("%g" % v) for v in tw) + " +no_defs")
    a = c.area_of_use
    unit = c.axis_info[0].unit_name
    out.append({
        "code": code, "name": c.name,
        "kind": "geographic" if c.is_geographic else "projected",
        "unit": "degree" if c.is_geographic else unit,
        "proj4": p4,
        "wkt": c.to_wkt("WKT1_ESRI"),
        "bounds": [round(a.west, 3), round(a.south, 3), round(a.east, 3), round(a.north, 3)] if a else None,
        "axisFlip": ("+axis=wsu" in p4),
    })
with open("app/js/crs-db.js", "w") as f:
    f.write("// Generated by tools/build_crs_db.py from the EPSG registry (via PROJ). Do not edit by hand.\n")
    f.write("export const CRS_DB = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(len(out), "systems written")
for o in out:
    if o["code"] in (20935, 3988, 4209, 32735, 21036, 22235, 2049):
        print(o["code"], o["name"], "|", o["proj4"], "|", o["unit"], o["bounds"])
